const { DataTypes } = require('sequelize');

module.exports = (sequelize) => {
  const money = (field) => ({ type: DataTypes.DECIMAL(12, 2), allowNull: false, defaultValue: 0, field });

  const Booking = sequelize.define('Booking', {
    id: { type: DataTypes.UUID, defaultValue: DataTypes.UUIDV4, primaryKey: true, allowNull: false },
    bookingCode: { type: DataTypes.STRING(30), allowNull: false, unique: true, field: 'booking_code' },
    customerId: { type: DataTypes.UUID, allowNull: false, field: 'customer_id' },
    craneId: { type: DataTypes.UUID, allowNull: false, field: 'crane_id' },
    ownerId: { type: DataTypes.UUID, allowNull: false, field: 'owner_id' },
    operatorId: { type: DataTypes.UUID, allowNull: true, field: 'operator_id' },
    craneType: { type: DataTypes.INTEGER, allowNull: false, field: 'crane_type' },
    capacity: { type: DataTypes.INTEGER, allowNull: false },

    siteName: { type: DataTypes.STRING(150), allowNull: true, field: 'site_name' },
    siteAddress: { type: DataTypes.TEXT, allowNull: false, field: 'site_address' },
    latitude: { type: DataTypes.DECIMAL(10, 7), allowNull: false },
    longitude: { type: DataTypes.DECIMAL(10, 7), allowNull: false },
    distanceKm: { type: DataTypes.DECIMAL(8, 2), allowNull: true, field: 'distance_km' },

    startType: { type: DataTypes.STRING(12), allowNull: false, field: 'start_type' },
    startAt: { type: DataTypes.DATE, allowNull: false, field: 'start_at' },
    endAt: { type: DataTypes.DATE, allowNull: false, field: 'end_at' },
    durationType: { type: DataTypes.STRING(12), allowNull: false, field: 'duration_type' },
    durationHours: { type: DataTypes.INTEGER, allowNull: false, field: 'duration_hours' },
    durationDays: { type: DataTypes.INTEGER, allowNull: true, field: 'duration_days' },

    hourlyRate: money('hourly_rate'),
    craneRental: money('crane_rental'),
    operatorCharges: money('operator_charges'),
    fuelCharges: money('fuel_charges'),
    otherCharges: money('other_charges'),
    totalAmount: money('total_amount'),
    advancePercent: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 20, field: 'advance_percent' },
    advanceAmount: money('advance_amount'),
    remainingAmount: money('remaining_amount'),

    paymentMethod: { type: DataTypes.STRING(20), allowNull: false, defaultValue: 'COD', field: 'payment_method' },
    paymentStatus: { type: DataTypes.STRING(20), allowNull: false, defaultValue: 'pending', field: 'payment_status' },
    paidAmount: money('paid_amount'),

    specialRequirements: { type: DataTypes.TEXT, allowNull: true, field: 'special_requirements' },
    operatorStatus: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0, field: 'operator_status', comment: '0 awaiting operator, 1 accepted, 2 declined' },
    operatorRespondedAt: { type: DataTypes.DATE, allowNull: true, field: 'operator_responded_at' },
    operatorDeclineReason: { type: DataTypes.TEXT, allowNull: true, field: 'operator_decline_reason' },
    enRouteAt: { type: DataTypes.DATE, allowNull: true, field: 'en_route_at' },
    arrivedAt: { type: DataTypes.DATE, allowNull: true, field: 'arrived_at' },
    arrivalConfirmedAt: { type: DataTypes.DATE, allowNull: true, field: 'arrival_confirmed_at' },
    arrivalConfirmedBy: { type: DataTypes.STRING(10), allowNull: true, field: 'arrival_confirmed_by' },
    checklist: { type: DataTypes.JSONB, allowNull: true },
    checklistCompletedAt: { type: DataTypes.DATE, allowNull: true, field: 'checklist_completed_at' },
    workStartedAt: { type: DataTypes.DATE, allowNull: true, field: 'work_started_at' },
    workEndedAt: { type: DataTypes.DATE, allowNull: true, field: 'work_ended_at' },
    waitingSeconds: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0, field: 'waiting_seconds' },
    waitingSince: { type: DataTypes.DATE, allowNull: true, field: 'waiting_since' },
    workingSeconds: { type: DataTypes.INTEGER, allowNull: true, field: 'working_seconds' },
    jobNotes: { type: DataTypes.TEXT, allowNull: true, field: 'job_notes' },
    completionOtp: { type: DataTypes.STRING(6), allowNull: true, field: 'completion_otp' },
    completionOtpExpiresAt: { type: DataTypes.DATE, allowNull: true, field: 'completion_otp_expires_at' },
    completionOtpAttempts: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0, field: 'completion_otp_attempts' },
    completionRequestedAt: { type: DataTypes.DATE, allowNull: true, field: 'completion_requested_at' },
    completedAt: { type: DataTypes.DATE, allowNull: true, field: 'completed_at' },
    finalAmount: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'final_amount' },
    platformFeePercent: { type: DataTypes.DECIMAL(5, 2), allowNull: true, field: 'platform_fee_percent' },
    platformFeeAmount: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'platform_fee_amount' },
    deductionsAmount: { type: DataTypes.DECIMAL(12, 2), allowNull: false, defaultValue: 0, field: 'deductions_amount' },
    netAmount: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'net_amount' },
    extraMinutes: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0, field: 'extra_minutes' },
    extraAmount: { type: DataTypes.DECIMAL(12, 2), allowNull: false, defaultValue: 0, field: 'extra_amount' },
    paymentReference: { type: DataTypes.STRING(40), allowNull: true, field: 'payment_reference' },
    paidAt: { type: DataTypes.DATE, allowNull: true, field: 'paid_at' },
    arrivingNotifiedAt: { type: DataTypes.DATE, allowNull: true, field: 'arriving_notified_at' },
    settlementStatus: { type: DataTypes.STRING(12), allowNull: false, defaultValue: 'pending', field: 'settlement_status' },
    settledAt: { type: DataTypes.DATE, allowNull: true, field: 'settled_at' },
    settlementId: { type: DataTypes.UUID, allowNull: true, field: 'settlement_id' },
    // booking made from a request (Rapido style)
    craneRequestId: { type: DataTypes.UUID, allowNull: true, field: 'crane_request_id' },
    distanceCharge: money('distance_charge'),
    paymentDueAt: { type: DataTypes.DATE, allowNull: true, field: 'payment_due_at' },
    advancePaidAt: { type: DataTypes.DATE, allowNull: true, field: 'advance_paid_at' },
    platformCollectedAmount: money('platform_collected_amount'),
    // bill: owner charges and GST copied when the booking is made (see services/billing.js)
    charges: { type: DataTypes.JSONB, allowNull: true },
    chargesAmount: money('charges_amount'),
    gstPercent: { type: DataTypes.DECIMAL(5, 2), allowNull: false, defaultValue: 0, field: 'gst_percent' },
    gstAmount: money('gst_amount'),
    subtotalAmount: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'subtotal_amount' },
    ownerShareAmount: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'owner_share_amount' },
    paymentCollectedBy: { type: DataTypes.STRING(10), allowNull: true, field: 'payment_collected_by' },
    // operator commission, set by the owner once the job is assigned
    operatorCommissionType: { type: DataTypes.STRING(10), allowNull: true, field: 'operator_commission_type' },
    operatorCommissionValue: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'operator_commission_value' },
    operatorCommissionAmount: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'operator_commission_amount' },
    operatorSettlementStatus: { type: DataTypes.STRING(12), allowNull: false, defaultValue: 'pending', field: 'operator_settlement_status' },
    operatorSettledAt: { type: DataTypes.DATE, allowNull: true, field: 'operator_settled_at' },
    operatorSettlementId: { type: DataTypes.UUID, allowNull: true, field: 'operator_settlement_id' },
    status: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0 },
    requestExpiresAt: { type: DataTypes.DATE, allowNull: true, field: 'request_expires_at' },
    acceptedAt: { type: DataTypes.DATE, allowNull: true, field: 'accepted_at' },
    declinedAt: { type: DataTypes.DATE, allowNull: true, field: 'declined_at' },
    declineReason: { type: DataTypes.TEXT, allowNull: true, field: 'decline_reason' },
    expiredAt: { type: DataTypes.DATE, allowNull: true, field: 'expired_at' },
    cancelledAt: { type: DataTypes.DATE, allowNull: true, field: 'cancelled_at' },
    cancelledBy: { type: DataTypes.STRING(12), allowNull: true, field: 'cancelled_by' },
    cancelReason: { type: DataTypes.TEXT, allowNull: true, field: 'cancel_reason' }
  }, {
    tableName: 'bookings',
    underscored: true,
    timestamps: true
  });

  return Booking;
};
